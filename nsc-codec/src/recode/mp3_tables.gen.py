#!/usr/bin/env python3
"""Generate src/recode/mp3_tables.rs from minimp3 (CC0 1.0, https://github.com/lieff/minimp3).

    python3 src/recode/mp3_tables.gen.py path/to/minimp3.h > src/recode/mp3_tables.rs

minimp3 stores the ISO/IEC 11172-3 Huffman code books as decoding trees. This walks every tree
exhaustively to list each code word, checks that every book is a complete prefix code, and writes
the books as (code, length) per symbol — the form a re-encoder needs. The scale-factor band
tables are copied as they are.
"""
import re
import sys

src = open(sys.argv[1]).read()


def arr(name):
    m = re.search(r"static const \w+ " + re.escape(name) + r"\s*\[[^\]]*\]\s*(?:\[[^\]]*\])?\s*=\s*\{(.*?)\};", src, re.S)
    assert m, name
    return [int(x) for x in re.findall(r"-?\d+", m.group(1))]


tabs, tab32, tab33, tabindex, linbits = arr("tabs"), arr("tab32"), arr("tab33"), arr("tabindex"), arr("g_linbits")
scf_long, scf_short, scf_part = arr("g_scf_long"), arr("g_scf_short"), arr("g_scf_partitions")
assert len(scf_long) == 8 * 23 and len(scf_short) == 8 * 40 and len(scf_part) == 3 * 28


def pair_book(tn):
    """{(x, y): (code, length)} of pair table `tn`."""
    base, out = tabindex[tn], {}

    def walk(off, w, prefix, plen):
        for v in range(1 << w):
            leaf = tabs[base + off + v]
            if leaf < 0:  # a pointer: this stage's w bits are consumed, the next stage reads (leaf & 7)
                walk(-(leaf >> 3), leaf & 7, (prefix << w) | v, plen + w)
            else:
                n = leaf >> 8
                key = (((prefix << w) | v) >> (w - n), plen + n)
                sym = (leaf & 15, (leaf >> 4) & 15)
                assert out.get(key, sym) == sym
                out[key] = sym

    walk(0, 5, 0, 0)
    assert abs(sum(2.0 ** -n for (_, n) in out) - 1.0) < 1e-12, tn  # complete prefix code
    book = {sym: key for key, sym in out.items()}
    assert len(book) == len(out), tn
    return book


def quad_book(tab):
    """{flags (v<<3 | w<<2 | x<<1 | y): (code, length)} of a count1 table."""
    out = {}
    for v in range(16):
        leaf = tab[v]
        if leaf & 8:
            n = leaf & 7
            out[(v >> (4 - n), n)] = leaf >> 4
        else:
            k = leaf & 3
            for u in range(1 << k):
                leaf2 = tab[(leaf >> 3) + u]
                n = leaf2 & 7
                out[(((v << k) | u) >> (4 + k - n), n)] = leaf2 >> 4
    assert abs(sum(2.0 ** -n for (_, n) in out) - 1.0) < 1e-12
    book = {sym: key for key, sym in out.items()}
    assert len(book) == 16
    return book


TREES = [1, 2, 3, 5, 6, 7, 8, 9, 10, 11, 12, 13, 15, 16, 24]
books = {t: pair_book(t) for t in TREES}
assert books[1] == {(0, 0): (1, 1), (0, 1): (1, 3), (1, 0): (1, 2), (1, 1): (0, 3)}  # ISO table 1
qa, qb = quad_book(tab32), quad_book(tab33)
assert qa[0] == (1, 1) and all(qb[f] == (15 - f, 4) for f in range(16))

print("//! MPEG audio Layer III tables (ISO/IEC 11172-3 and 13818-3): the Huffman code books as")
print("//! (code, length) per symbol, and the scale-factor band partitions.")
print("//!")
print("//! Generated by `mp3_tables.gen.py` from minimp3 (CC0 1.0), whose decoding trees are walked")
print("//! exhaustively; every book is checked to be a complete prefix code. Do not edit.")
print()
print("/// Code tree used by each of the 32 pair tables (index into [`BOOKS`]); `NONE` for table 0 (all")
print("/// zero, no bits) and the unused tables 4 and 14.")
print("pub const NONE: u8 = 255;")
tree_of = []
for t in range(32):
    if t in (0, 4, 14):
        tree_of.append(255)
    elif t >= 24:
        tree_of.append(TREES.index(24))
    elif t >= 16:
        tree_of.append(TREES.index(16))
    else:
        tree_of.append(TREES.index(t))
print(f"pub const TREE_OF: [u8; 32] = {tree_of};")
print("/// Escape bits after a value of 15, per pair table.")
print(f"pub const LINBITS: [u8; 32] = {linbits};")
print("/// Largest value (before escape bits) of each code tree.")
print(f"pub const TREE_MAX: [u8; {len(TREES)}] = {[max(max(s) for s in books[t]) for t in TREES]};")
print("/// The code trees: (code, length) of the pair (x, y) at index `x * 16 + y`; length 0 = no such pair.")
print(f"pub static BOOKS: [[(u32, u8); 256]; {len(TREES)}] = [")
for t in TREES:
    row = [books[t].get((i >> 4, i & 15), (0, 0)) for i in range(256)]
    print("    [" + ", ".join(f"({c}, {n})" for c, n in row) + "],")
print("];")
print("/// The two count1 books (A, B): (code, length) of the quadruple with nonzero flags")
print("/// `v << 3 | w << 2 | x << 1 | y`.")
print("pub static QUADS: [[(u32, u8); 16]; 2] = [")
for q in (qa, qb):
    print("    [" + ", ".join(f"({c}, {n})" for c, n in (q[f] for f in range(16))) + "],")
print("];")
print()
print("/// Row of the band tables for (version, sample-rate index): MPEG-2.5 11.025/12 kHz, MPEG-2.5")
print("/// 8 kHz, MPEG-2 22.05, 24, 16 kHz, MPEG-1 44.1, 48, 32 kHz.")
print("/// Widths of the long-block scale-factor bands (22 bands, 576 lines), per row.")
print("pub static SFB_LONG: [[u8; 22]; 8] = [")
for r in range(8):
    row = scf_long[r * 23:r * 23 + 22]
    assert sum(row) == 576, (r, sum(row))
    print(f"    {row},")
print("];")
print("/// Widths of the short-block scale-factor bands (13 bands per window, 192 lines), per row.")
print("pub static SFB_SHORT: [[u8; 13]; 8] = [")
for r in range(8):
    row = scf_short[r * 40:r * 40 + 39]
    assert all(row[i] == row[i + 1] == row[i + 2] for i in range(0, 39, 3))
    row = row[0::3]
    assert sum(row) == 192, (r, sum(row))
    print(f"    {row},")
print("];")
print("/// Scale-factor partitions (how many scale factors share each of the four bit widths), per")
print("/// block layout (0 long, 1 mixed, 2 short): first the MPEG-1 partition, then the six MPEG-2 ones.")
print("pub static SCF_PARTITIONS: [[[u8; 4]; 7]; 3] = [")
for r in range(3):
    row = scf_part[r * 28:(r + 1) * 28]
    print("    [" + ", ".join(str(row[i:i + 4]) for i in range(0, 28, 4)) + "],")
print("];")
