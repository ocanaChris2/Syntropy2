#!/usr/bin/env python3
"""Generate src/recode/h264_vlc_tables.rs from OpenH264 (BSD-2-Clause, github.com/cisco/openh264).

    python3 src/recode/h264_vlc_tables.gen.py path/to/openh264 > src/recode/h264_vlc_tables.rs

The codes are those of ITU-T H.264 clause 9.2 (CAVLC): tables 9-5 (coeff_token), 9-7 to 9-9
(total_zeros), 9-10 (run_before), and 9-4 (the coded block pattern's code numbers).
"""
import re
import sys

root = sys.argv[1]
enc = open(f"{root}/codec/encoder/core/src/encoder_data_tables.cpp").read()
dec = open(f"{root}/codec/decoder/core/src/decoder_data_tables.cpp").read()


def ints(src, name):
    m = re.search(re.escape(name) + r"\s*(?:\[[^\]]*\]\s*)+=\s*\{(.*?)\};", src, re.S)
    assert m, name
    body = re.sub(r"//[^\n]*", "", m.group(1))
    return [int(x) for x in re.findall(r"-?\d+", body)]


def pairs(v):
    return [(v[2 * i], v[2 * i + 1]) for i in range(len(v) // 2)]


def prefix_free(codes, what):
    """codes: (value, length), length 0 = unused."""
    used = sorted({(format(v, "b").zfill(n)) for v, n in codes if n}, key=len)
    assert len(used) == sum(1 for _, n in codes if n), f"{what}: duplicate codes"
    for i, a in enumerate(used):
        for b in used[i + 1:]:
            assert not b.startswith(a), f"{what}: {a} is a prefix of {b}"
    return sum(2.0 ** -len(c) for c in used)


token = pairs(ints(enc, "g_kuiVlcCoeffToken"))
assert len(token) == 5 * 17 * 4
tz = pairs(ints(enc, "g_kuiVlcTotalZeros"))
assert len(tz) == 16 * 16
tzdc = pairs(ints(enc, "g_kuiVlcTotalZerosChromaDc"))
assert len(tzdc) == 4 * 4
run = pairs(ints(enc, "g_kuiVlcRunBefore"))
assert len(run) == 8 * 15
cbp = {n: ints(dec, n) for n in ["g_kuiIntra4x4CbpTable", "g_kuiInterCbpTable", "g_kuiIntra4x4CbpTable400", "g_kuiInterCbpTable400"]}
assert [len(v) for v in cbp.values()] == [48, 48, 16, 16]
for n, v in cbp.items():
    assert sorted(v) == sorted(set(v)), n  # one code number per pattern

# every table is a prefix code; a token exists exactly when trailing ones <= min(3, total)
for nc in range(5):
    t = token[nc * 68:(nc + 1) * 68]
    for total in range(17):
        for t1 in range(4):
            v, n = t[total * 4 + t1]
            ok = t1 <= min(3, total) and (nc != 4 or total <= 4)
            assert (n > 0) == ok, (nc, total, t1)
    k = prefix_free(t, f"coeff_token {nc}")
    assert k <= 1.0 + 1e-9, (nc, k)
for i in range(1, 16):
    row = tz[i * 16:(i + 1) * 16]
    assert all((n > 0) == (z <= 16 - i) for z, (_, n) in enumerate(row)), i
    assert prefix_free(row, f"total_zeros {i}") <= 1.0 + 1e-9, i
for i in range(1, 4):
    row = tzdc[i * 4:(i + 1) * 4]
    assert all((n > 0) == (z <= 4 - i) for z, (_, n) in enumerate(row)), i
    assert prefix_free(row, f"total_zeros dc {i}") <= 1.0 + 1e-9, i
for i in range(1, 8):
    row = run[i * 15:(i + 1) * 15]
    assert all((n > 0) == (r <= (i if i < 7 else 14)) for r, (_, n) in enumerate(row)), i
    prefix_free(row, f"run_before {i}")


def table(name, doc, rows, per):
    print(f"/// {doc}")
    print(f"pub static {name}: [[(u8, u8); {per}]; {len(rows) // per}] = [")
    for i in range(0, len(rows), per):
        print("    [" + ", ".join(f"({v}, {n})" for v, n in rows[i:i + per]) + "],")
    print("];")


print("//! H.264 CAVLC code tables (ITU-T H.264 clause 9.2), as (code, length) with length 0 where")
print("//! there is no code.")
print("//!")
print("//! Generated by `h264_vlc_tables.gen.py` from OpenH264 (BSD-2-Clause, Cisco Systems). Do not edit.")
print()
print("/// `coeff_token` by table (0: nC 0..2, 1: nC 2..4, 2: nC 4..8, 3: nC 8 and up, 4: chroma DC),")
print("/// then `[total_coeff][trailing_ones]`.")
print("pub static COEFF_TOKEN: [[[(u8, u8); 4]; 17]; 5] = [")
for nc in range(5):
    print("    [")
    for total in range(17):
        row = token[nc * 68 + total * 4:nc * 68 + total * 4 + 4]
        print("        [" + ", ".join(f"({v}, {n})" for v, n in row) + "],")
    print("    ],")
print("];")
table("TOTAL_ZEROS", "`total_zeros` of a block of up to 16 coefficients: `[total_coeff][total_zeros]` (total_coeff 1..=15).", tz, 16)
table("TOTAL_ZEROS_DC", "`total_zeros` of a 4:2:0 chroma DC block: `[total_coeff][total_zeros]` (total_coeff 1..=3).", tzdc, 4)
table("RUN_BEFORE", "`run_before`: `[min(zeros_left, 7)][run_before]` (zeros_left from 1).", run, 15)
print("/// The coded block pattern of each code number: intra 4x4/8x8 and inter macroblocks, with")
print("/// chroma (4:2:0) and without (monochrome).")
print(f"pub static CBP_INTRA: [u8; 48] = {cbp['g_kuiIntra4x4CbpTable']};")
print(f"pub static CBP_INTER: [u8; 48] = {cbp['g_kuiInterCbpTable']};")
print(f"pub static CBP_INTRA_GRAY: [u8; 16] = {cbp['g_kuiIntra4x4CbpTable400']};")
print(f"pub static CBP_INTER_GRAY: [u8; 16] = {cbp['g_kuiInterCbpTable400']};")
