#!/usr/bin/env python3
"""Generate src/recode/aac_tables.rs from JAAD (public domain, github.com/DV8FromTheWorld/JAADec).

    python3 src/recode/aac_tables.gen.py path/to/jaad > src/recode/aac_tables.rs

JAAD lists the ISO/IEC 14496-3 Huffman code books as {length, code word, values…}. This turns them
into (code, length) per symbol index — the form a re-encoder needs — checks that every book is a
complete prefix code over exactly its symbol set, and copies the scale-factor band offsets.
"""
import re
import sys

d = sys.argv[1]
cb_src = open(f"{d}/Codebooks.java").read()
sfb_src = open(f"{d}/ScaleFactorBands.java").read()


def table(src, name):
    m = re.search(r"int\[\]\[\] " + name + r"\s*=\s*\{(.*?)\n\t\};", src, re.S)
    assert m, name
    return [[int(x) for x in re.findall(r"-?\d+", row)] for row in re.findall(r"\{([^{}]*)\}", m.group(1))]


def ints(src, name):
    m = re.search(r"int\[\] " + name + r"\s*=\s*\{(.*?)\};", src, re.S)
    assert m, name
    return [int(x) for x in re.findall(r"-?\d+", m.group(1))]


# (dimension, signed, largest absolute value) of spectral books 1..11
SHAPE = [(4, True, 1), (4, True, 1), (4, False, 2), (4, False, 2), (2, True, 4), (2, True, 4), (2, False, 7), (2, False, 7), (2, False, 12), (2, False, 12), (2, False, 16)]


def index(vals, signed, lav):
    """Symbol index of a tuple: its values as digits, most significant first."""
    base = 2 * lav + 1 if signed else lav + 1
    i = 0
    for v in vals:
        i = i * base + (v + lav if signed else v)
    return i


books = []
for k, (dim, signed, lav) in enumerate(SHAPE):
    rows = table(cb_src, f"HCB{k + 1}")
    base = 2 * lav + 1 if signed else lav + 1
    book = [None] * base ** dim
    for row in rows:
        n, code, vals = row[0], row[1], row[2:2 + dim]
        assert all(abs(v) <= lav and (signed or v >= 0) for v in vals), (k, row)
        i = index(vals, signed, lav)
        assert book[i] is None, (k, row)
        book[i] = (code, n)
    assert all(b is not None for b in book), k
    assert abs(sum(2.0 ** -n for _, n in book) - 1.0) < 1e-12, k  # complete prefix code
    books.append(book)
sf = [None] * 121
for n, code, val in table(cb_src, "HCB_SF"):
    assert sf[val] is None
    sf[val] = (code, n)
assert all(s is not None for s in sf) and abs(sum(2.0 ** -n for _, n in sf) - 1.0) < 1e-12

long_names = re.search(r"int\[\]\[\] SWB_OFFSET_LONG_WINDOW\s*=\s*\{(.*?)\};", sfb_src, re.S).group(1).replace("\n", " ").replace("\t", "").split(",")
short_names = re.search(r"int\[\]\[\] SWB_OFFSET_SHORT_WINDOW\s*=\s*\{(.*?)\};", sfb_src, re.S).group(1).replace("\n", " ").replace("\t", "").split(",")
long_cnt, short_cnt = ints(sfb_src, "SWB_LONG_WINDOW_COUNT"), ints(sfb_src, "SWB_SHORT_WINDOW_COUNT")
long_names = [n.strip() for n in long_names if n.strip()]
short_names = [n.strip() for n in short_names if n.strip()]
assert len(long_names) == len(short_names) == len(long_cnt) == len(short_cnt) == 12

print("//! AAC tables (ISO/IEC 14496-3): the spectral and scale-factor Huffman code books as (code,")
print("//! length) per symbol, and the scale-factor band offsets per sampling-frequency index.")
print("//!")
print("//! Generated by `aac_tables.gen.py` from JAAD (public domain); every book is checked to be a")
print("//! complete prefix code over exactly its symbols. Do not edit.")
print()
print("/// Spectral books 1..=11: (values per code word, signed, largest absolute value). A symbol's")
print("/// index is its values as digits (offset by the largest value when signed), first value first.")
print(f"pub const SHAPE: [(usize, bool, u8); 11] = {[(d_, 'true' if s else 'false', l) for d_, s, l in SHAPE]};".replace("'", ""))
for k, book in enumerate(books):
    print(f"static HCB{k + 1}: [(u32, u8); {len(book)}] = [" + ", ".join(f"({c}, {n})" for c, n in book) + "];")
print("/// The spectral books (index 0 = book 1).")
print("pub static SPECTRAL: [&[(u32, u8)]; 11] = [" + ", ".join(f"&HCB{k + 1}" for k in range(11)) + "];")
print("/// The scale-factor book: (code, length) of difference `index - 60`.")
print(f"pub static SCALEFACTOR: [(u32, u8); 121] = [" + ", ".join(f"({c}, {n})" for c, n in sf) + "];")
print("/// Scale-factor band offsets of long windows (1024 lines) per sampling-frequency index 0..12")
print("/// (96, 88.2, 64, 48, 44.1, 32, 24, 22.05, 16, 12, 11.025, 8 kHz): `count + 1` offsets each.")
print("pub static SWB_LONG: [&[u16]; 12] = [")
for name, cnt in zip(long_names, long_cnt):
    off = ints(sfb_src, name)[:cnt + 1]
    assert off[0] == 0 and off[-1] == 1024 and all(a < b for a, b in zip(off, off[1:])) and all(o % 4 == 0 for o in off), name
    print(f"    &{off},")
print("];")
print("/// Scale-factor band offsets of short windows (128 lines) per sampling-frequency index.")
print("pub static SWB_SHORT: [&[u16]; 12] = [")
for name, cnt in zip(short_names, short_cnt):
    off = ints(sfb_src, name)[:cnt + 1]
    assert off[0] == 0 and off[-1] == 128 and all(a < b for a, b in zip(off, off[1:])) and all(o % 4 == 0 for o in off), name
    print(f"    &{off},")
print("];")
