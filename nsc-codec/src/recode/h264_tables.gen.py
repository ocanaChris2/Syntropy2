#!/usr/bin/env python3
"""Generate src/recode/h264_tables.rs from OpenH264 (BSD-2-Clause, github.com/cisco/openh264).

    python3 src/recode/h264_tables.gen.py path/to/openh264 > src/recode/h264_tables.rs

The numbers are those of ITU-T H.264 (tables 9-12 to 9-33 for the CABAC context initialisation,
9-44 and 9-45 for the arithmetic coder, 9-43 for the 8x8 significance contexts).
"""
import re
import sys

root = sys.argv[1]
common = open(f"{root}/codec/common/src/common_tables.cpp").read()
basis = open(f"{root}/codec/decoder/core/inc/wels_common_basis.h").read()


def ints(src, name):
    m = re.search(re.escape(name) + r"\s*(?:\[[^\]]*\]\s*)+=\s*\{(.*?)\};", src, re.S)
    assert m, name
    # CTX_NA marks the contexts an I slice never uses; any value will do there
    body = re.sub(r"//[^\n]*", "", m.group(1)).replace("CTX_NA", "0")
    return [int(x) for x in re.findall(r"-?\d+", body)]


init = ints(common, "g_kiCabacGlobalContextIdx")
assert len(init) == 460 * 4 * 2, len(init)
lps = ints(common, "g_kuiCabacRangeLps")
assert len(lps) == 64 * 4
trans = ints(common, "g_kuiStateTransTable")
assert len(trans) == 64 * 2
sig8 = ints(basis, "g_kuiIdx2CtxSignificantCoeffFlag8x8")
last8 = ints(basis, "g_kuiIdx2CtxLastSignificantCoeffFlag8x8")
assert len(sig8) == 64 and len(last8) == 64 and max(sig8) == 14 and max(last8) == 8
# the state machine: the LPS transition never raises the state, the MPS one moves up by one
assert all(trans[2 * s] <= s and trans[2 * s + 1] == min(s + 1, 62) for s in range(63)) and trans[126:] == [63, 63]

print("//! H.264 CABAC tables (ITU-T H.264 clause 9.3): context initialisation, the arithmetic")
print("//! coder's LPS ranges and state transitions, and the 8x8 significance context maps.")
print("//!")
print("//! Generated by `h264_tables.gen.py` from OpenH264 (BSD-2-Clause, Cisco Systems). Do not edit.")
print()
print("/// Contexts 0..460 (all a 4:2:0 or monochrome stream uses).")
print("pub const CONTEXTS: usize = 460;")
print("/// (m, n) of every context for I slices (index 0) and `cabac_init_idc` 0..=2 (indexes 1..=3).")
print("pub static INIT: [[(i8, i8); 4]; CONTEXTS] = [")
for c in range(460):
    row = init[c * 8:(c + 1) * 8]
    print("    [" + ", ".join(f"({row[2 * k]}, {row[2 * k + 1]})" for k in range(4)) + "],")
print("];")
print("/// `rangeTabLPS[state][(range >> 6) & 3]`.")
print("pub static RANGE_LPS: [[u8; 4]; 64] = [")
for s in range(64):
    print(f"    {lps[4 * s:4 * s + 4]},")
print("];")
print("/// The next state after coding the less probable symbol in each state (after the more")
print("/// probable one: `min(state + 1, 62)`).")
print(f"pub static NEXT_LPS: [u8; 64] = {[trans[2 * s] for s in range(64)]};")
print("/// Context increment of `significant_coeff_flag` / `last_significant_coeff_flag` by position")
print("/// in a frame-coded 8x8 block.")
print(f"pub static SIG_8X8: [u8; 63] = {sig8[:63]};")
print(f"pub static LAST_8X8: [u8; 63] = {last8[:63]};")
